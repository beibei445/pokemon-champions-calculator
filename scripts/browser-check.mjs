import {chromium} from '@playwright/test';
import {mkdirSync,writeFileSync} from 'node:fs';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'});
await page.locator('h1').waitFor();
mkdirSync('verification',{recursive:true});
await page.screenshot({path:'verification/desktop.png',fullPage:true});
await page.getByRole('button',{name:'我方宝可梦',exact:true}).click();
await page.getByRole('textbox',{name:'搜索我方宝可梦'}).fill('水箭龟');
await page.locator('.picker-options [role=option]').click();
await page.getByRole('button',{name:'Mega',exact:true}).first().click();
await page.locator('.left .pokemon-english').filter({hasText:'Blastoise-Mega'}).waitFor();
await page.getByRole('button',{name:'普通形态',exact:true}).first().click();
await page.getByRole('button',{name:'我方招式',exact:true}).click();
await page.getByRole('textbox',{name:'搜索我方招式'}).fill('水炮');
await page.getByRole('option',{name:'水炮 Hydro Pump 水',exact:true}).click();
await page.getByRole('button',{name:'双打',exact:true}).click();
await page.getByLabel('天气',{exact:true}).selectOption('Rain');
await page.getByRole('button',{name:'交换双方',exact:true}).click();
if(!(await page.locator('.right .pokemon-english').innerText()).includes('Blastoise'))throw new Error('Swap did not exchange sets');
await page.getByRole('button',{name:'重置',exact:true}).click();
await page.getByRole('spinbutton',{name:'我方攻击能力点数值'}).fill('32');
if(await page.getByRole('spinbutton',{name:'我方攻击能力点数值'}).inputValue()!=='2')throw new Error('Stat budget not enforced');
await page.getByRole('button',{name:'查看伤害细节',exact:true}).click();
await page.getByRole('button',{name:'计算条件',exact:true}).click();
await page.getByRole('button',{name:'计算说明',exact:true}).click();
await page.getByRole('dialog').waitFor();
await page.keyboard.press('Escape');
await page.getByRole('button',{name:'重置',exact:true}).click();
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'verification/mobile.png',fullPage:true});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
if(overflow)throw new Error('Mobile has horizontal overflow');
await page.setViewportSize({width:1440,height:1100});
await page.evaluate(()=>{document.documentElement.style.fontSize='32px'});
await page.screenshot({path:'verification/text-200.png',fullPage:true});
if(errors.length)throw new Error(errors.join('\n'));
writeFileSync('verification/browser-results.json',JSON.stringify({desktop:1440,mobile:390,errors,checks:['species search','Mega switch','move search','doubles','weather','swap','reset','66 point limit','details','rules dialog','mobile overflow']},null,2));
console.log('Browser checks passed; desktop/mobile screenshots saved.');
await browser.close();
